import { deleteCookie, setCookie, getCookie } from './cookie';
import { TIngredient, TOrder, TOrdersData, TUser } from './types';

const URL = process.env.BURGER_API_URL;

const checkResponse = <T>(res: Response): Promise<T> =>
  res.ok ? res.json() : res.json().then((err) => Promise.reject(err));

type TServerResponse<T> = {
  success: boolean;
} & T;

type TRefreshResponse = TServerResponse<{
  refreshToken: string;
  accessToken: string;
}>;

let refreshTokenRequest: Promise<TRefreshResponse> | null = null;

const clearAuthTokens = () => {
  deleteCookie('accessToken');
  localStorage.removeItem('refreshToken');
};

const isInvalidRefreshError = (err: unknown) => {
  if (!err || typeof err !== 'object') return false;
  const error = err as { success?: boolean; message?: string };
  if (error.success === false) return true;
  return Boolean(
    error.message && !/failed to fetch|network|load failed/i.test(error.message)
  );
};

export const refreshToken = (): Promise<TRefreshResponse> =>
  fetch(`${URL}/auth/token`, {
    method: 'POST',
    headers: {
      'Content-Type': 'application/json;charset=utf-8'
    },
    body: JSON.stringify({
      token: localStorage.getItem('refreshToken')
    })
  })
    .then((res) => checkResponse<TRefreshResponse>(res))
    .then((refreshData) => {
      if (!refreshData.success) {
        return Promise.reject(refreshData);
      }
      localStorage.setItem('refreshToken', refreshData.refreshToken);
      setCookie('accessToken', refreshData.accessToken);
      return refreshData;
    })
    .catch((err) => {
      if (isInvalidRefreshError(err)) {
        clearAuthTokens();
      }
      return Promise.reject(err);
    });

const getHeaderValue = (
  headers: HeadersInit | undefined,
  name: string
): string | null => {
  if (!headers) return null;
  if (headers instanceof Headers) return headers.get(name);
  if (Array.isArray(headers)) {
    const pair = headers.find(
      ([key]) => key.toLowerCase() === name.toLowerCase()
    );
    return pair?.[1] ?? null;
  }
  return headers[name] ?? null;
};

const hasRefreshToken = () => Boolean(localStorage.getItem('refreshToken'));

const refreshTokenOnce = () => {
  if (!refreshTokenRequest) {
    refreshTokenRequest = refreshToken().finally(() => {
      refreshTokenRequest = null;
    });
  }
  return refreshTokenRequest;
};

const withAuthorization = (
  options: RequestInit,
  accessToken: string
): RequestInit => ({
  ...options,
  headers: {
    ...(options.headers instanceof Headers
      ? Object.fromEntries(options.headers.entries())
      : Array.isArray(options.headers)
        ? Object.fromEntries(options.headers)
        : options.headers),
    authorization: accessToken
  }
});

export const fetchWithRefresh = async <T>(
  url: RequestInfo,
  options: RequestInit
) => {
  const authorization = getHeaderValue(options.headers, 'authorization');
  const requestOptions =
    !authorization && hasRefreshToken()
      ? withAuthorization(options, (await refreshTokenOnce()).accessToken)
      : { ...options };

  try {
    const res = await fetch(url, requestOptions);
    return await checkResponse<T>(res);
  } catch (err) {
    if ((err as { message: string }).message === 'jwt expired') {
      const refreshData = await refreshTokenOnce();
      const res = await fetch(
        url,
        withAuthorization(requestOptions, refreshData.accessToken)
      );
      return await checkResponse<T>(res);
    } else {
      return Promise.reject(err);
    }
  }
};

